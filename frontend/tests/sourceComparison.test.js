import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { VERSION, equivalent, canonicalRow } from '../src/lib/sourceComparison.js'

const require = createRequire(import.meta.url)
const backend = require('../../backend/pb_hooks/lib/source_comparison.js')
const policy = { tone_equivalence: true, reading_fields: ['记音'], comparison_version: VERSION }

test('browser, JSVM and offline comparison stay byte-for-byte in sync', () => {
  const source = readFileSync(new URL('../../backend/pb_hooks/lib/source_comparison.js', import.meta.url), 'utf8')
  const generated = '// Generated by scripts/sync_source_comparison.py; edit the JSVM source.\n' + source.replace('module.exports = sourceComparison', 'export const { VERSION, nfc, validToneForm, toneKey, fieldKey, equivalent, canonicalRow } = sourceComparison')
  assert.equal(readFileSync(new URL('../src/lib/sourceComparison.js', import.meta.url), 'utf8'), generated)
})

test('only explicitly segmented tone suffixes in opted-in reading fields compare equal', () => {
  for (const [a, b, field, expected] of [
    ['ka533', 'ka⁵³³', '记音', true], ['ka533', 'ka453', '记音', false],
    ['ka533', 'ga533', '记音', false], ['ka533', 'ka53', '记音', false],
    ['ka533', 'ka⁵³³', '释义', false], ['ka533 ga21', 'ka⁵³³ ga²¹', '记音', true],
    ['ka533ga21', 'ka⁵³³ga²¹', '记音', false], ['ka53³', 'ka⁵³³', '记音', false],
    ['编号533', '编号⁵³³', '记音', false], ['ka533/ga21', 'ka⁵³³/ga²¹', '记音', false],
    ['kʰa533', 'kha533', '记音', false], ['ka533', 'kɑ533', '记音', false],
    ['ã533', 'a\u0303533', '记音', true], ['', '', '记音', true]
  ]) {
    assert.equal(equivalent(a, b, field, policy), expected, `${field}: ${a} / ${b}`)
    assert.equal(backend.equivalent(a, b, field, policy), expected)
  }
  assert.equal(equivalent('ka533', 'ka⁵³³', '记音', null), false)
  assert.equal(equivalent('Ａ533', 'A533', '记音', policy), false)
  assert.equal(equivalent('ka533 ga21', 'ka533  ga21', '记音', policy), false)
})

test('comparison never rewrites originals or folds unrelated fields', () => {
  const a = { 记音: 'ka533', 释义: '', 页码: '²' }
  const b = { 页码: '²', 释义: '', 记音: 'ka⁵³³' }
  assert.equal(canonicalRow(a, policy), canonicalRow(b, policy))
  assert.notEqual(canonicalRow(a, policy), canonicalRow({ ...b, 页码: '2' }, policy))
  assert.equal(a.记音, 'ka533')
  assert.equal(b.记音, 'ka⁵³³')
})
