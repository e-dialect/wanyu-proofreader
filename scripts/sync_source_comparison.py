"""Generate the standalone browser module from the JSVM/offline comparison core."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backend/pb_hooks/lib/source_comparison.js"
TARGET = ROOT / "frontend/src/lib/sourceComparison.js"


def expected():
    return "// Generated by scripts/sync_source_comparison.py; edit the JSVM source.\n" + SOURCE.read_text().replace(
        "module.exports = sourceComparison",
        "export const { VERSION, nfc, validToneForm, toneKey, fieldKey, equivalent, canonicalRow } = sourceComparison",
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        if TARGET.read_text() != expected():
            raise SystemExit("Comparison modules differ: run python3 scripts/sync_source_comparison.py")
    else:
        TARGET.write_text(expected())
